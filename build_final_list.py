    api = {e["base_id"]: e for e in json.load(open("api_pool.json"))}
    lm = json.load(open("listing_meta.json"))
    out = []
    missing = []
    for pid, (tech, note) in sorted(D.items()):
        e = lm.get(pid) or api.get(pid)
        if e is None:
            missing.append(pid)
            continue
        out.append({
            "id": pid,
            "title": e["title"],
            "authors": e.get("authors", []),
            "published": e["published"],
            "categories": e.get("categories", []),
            "summary": e.get("summary", ""),
            "techniques": tech,
            "note": note,
        })
    out.sort(key=lambda x: x["id"])
    json.dump(out, open("final_papers.json", "w"), ensure_ascii=False, indent=2)
    print("final papers:", len(out))
    if missing:
        print("MISSING metadata:", missing)
    # stats
    from collections import Counter
    c = Counter()
    for p in out:
        for t in p["techniques"]:
            c[t] += 1
    print(dict(c.most_common()))
    quant = [p["id"] for p in out if "quantization" in p["techniques"] or "mixed_precision" in p["techniques"]]
    print("quantization-related:", len(quant))

